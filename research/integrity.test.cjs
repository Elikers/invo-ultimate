const assert=require('node:assert/strict');
const I=require('./integrity.cjs');
const trades=[-1,-1,1,-1,-1,-1,3,1].map(grossPct=>({grossPct}));
const risk=I.streaks(trades,0);
assert.equal(risk.max_consecutive_losses,3);
assert.equal(risk.max_consecutive_wins,2);
assert.equal(risk.trades,8);
assert.ok(risk.max_drawdown_pct>0);
assert.equal(I.streaks([],8).max_drawdown_pct,null);
assert.equal(I.grade({closed_trades:0}).status,'INSUFFICIENT_SAMPLES');
const fake={closed_trades:100,period:[{count:50},{count:25,expectancyPct:0.1,profitFactor:1.2},{count:25,expectancyPct:0.1,profitFactor:1.2}],stress_bps:{'8':{expectancyPct:0.1},'16':{expectancyPct:0.01,profitFactor:1.2,maxDrawdownPct:12}}};
assert.equal(I.grade(fake).status,'PRELIMINARY_HISTORICAL_SCREEN_ONLY');
fake.stress_bps['16'].expectancyPct=-0.2;
assert.equal(I.grade(fake).status,'HISTORICAL_ROBUSTNESS_SCREEN_FAILED');
const report={schema:'invo-v6.4-loss-diagnosis-1',created_utc:new Date().toISOString(),markets:{BTC:{status:'ANALYZED',strategies:{fusion:fake}}}};
const out=I.build(report,null,null);
assert.equal(out.markets.BTC.strategies.fusion.grade.status,'HISTORICAL_ROBUSTNESS_SCREEN_FAILED');
assert.ok(out.flags.includes('COLLECTOR_HEARTBEAT_MISSING'));
assert.ok(out.flags.includes('FORWARD_SUMMARY_STALE_OR_MISSING'));
assert.throws(()=>I.build({},null,null),/wrong schema/);
console.log('v6.5 integrity and risk tests passed');
