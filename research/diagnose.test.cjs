const assert=require('node:assert/strict');
const D=require('./diagnose.cjs');
const C=require('../v61-core.js');
const b=Array.from({length:500},(_,i)=>({t:i*300000,o:100,h:100.3,l:99.7,c:100,v:30}));
assert.equal(C.valid(b),true);
const no=()=>null;
const empty=D.explain(b,'fusion',no);
assert.equal(empty.closed_trades,0);
assert.equal(empty.break_even_round_trip_cost_bps,null);
assert.equal(empty.stress_bps['8'].count,0);
const always=()=>({side:'LONG'});
const x=D.explain(b,'fusion',always);
assert.ok(x.closed_trades>0);
assert.equal(x.stress_bps['8'].count,x.closed_trades);
assert.equal(x.stress_bps['16'].count,x.closed_trades);
assert.ok(x.stress_bps['0'].expectancyPct>x.stress_bps['8'].expectancyPct);
assert.ok(x.stress_bps['8'].expectancyPct>x.stress_bps['16'].expectancyPct);
assert.ok(Math.abs(x.stress_bps['0'].expectancyPct-x.break_even_round_trip_cost_bps/100)<1e-10);
assert.equal(Object.values(x.exit_reasons).reduce((s,r)=>s+r.count,0),x.closed_trades);
assert.equal(x.side.LONG.count,x.closed_trades);
assert.equal(x.side.SHORT.count,0);
assert.equal(x.period.length,3);
assert.throws(()=>D.explain(b,'invalid',always),/Unknown strategy/);
assert.throws(()=>D.explain([b[0],...b.slice(2)],'fusion',always),/Invalid|discontinuous/);
console.log('v6.4 retrospective loss diagnostics tests passed');
