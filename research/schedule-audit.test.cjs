const assert=require('node:assert/strict'),A=require('./schedule-audit.cjs');
const now=Date.parse('2026-11-18T12:00:00Z');
const run=(event,age,conclusion='success',status='completed',schedule)=>({id:age,name:A.WORKFLOW,event,created_at:new Date(now-age).toISOString(),conclusion,status,...(schedule?{schedule}:{})});
let o=A.check([run('push',300000)],now);
assert.equal(o.status,'AWAITING_FIRST_SCHEDULE');assert.equal(o.alert,false);
o=A.check([run('push',3*3600000)],now);
assert.equal(o.status,'SCHEDULE_UNVERIFIED_OR_STALE');assert.equal(o.alert,true);
o=A.check([run('push',300000),run('schedule',1800000)],now);
assert.equal(o.status,'VERIFIED_SCHEDULE_RECENT');assert.equal(o.alert,false);
assert.equal(o.cadence.cadence_status,'TRIGGER_CRON_NOT_EXPOSED_BY_API');
assert.equal(o.cadence.observed_vs_nominal_ratio,null);
assert.equal(o.cadence.classified_poll_successes,0);
assert.equal(o.cadence.unclassified_scheduled_successes,1);
const poll=A.check([run('schedule',300000,'success','completed',A.POLL),run('schedule',60*60000,'success','completed',A.POLL)],now);
assert.equal(poll.cadence.cadence_status,'GAPS_OVER_25_MINUTES');
assert.equal(poll.cadence.successful_intervals_minutes[0],55);
assert.equal(poll.cadence.classified_poll_successes,2);
const mixed=A.check([run('schedule',300000,'success','completed',A.DAILY),run('schedule',20*60000,'success','completed',A.POLL)],now);
assert.equal(mixed.cadence.classified_poll_successes,1);
assert.equal(mixed.cadence.cadence_status,'TOO_FEW_CLASSIFIED_POLLS');
o=A.check([run('schedule',3*3600000)],now);
assert.equal(o.status,'SCHEDULE_UNVERIFIED_OR_STALE');
o=A.check([run('schedule',100000,'', 'in_progress')],now);
assert.equal(o.status,'SCHEDULED_RUN_IN_PROGRESS');assert.equal(o.alert,false);
o=A.check([run('schedule',100000,'failure')],now);assert.equal(o.alert,true);
o=A.check([],now);assert.equal(o.alert,true);
assert.throws(()=>A.check({},now),/Invalid GitHub/);
console.log('INVO v6.8.2 GitHub schedule event/provenance audit tests passed');
