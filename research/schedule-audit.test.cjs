const assert=require('node:assert/strict'),A=require('./schedule-audit.cjs');
const now=Date.parse('2026-11-18T12:00:00Z');
const run=(event,time,conclusion='success',status='completed')=>({id:123,name:A.WORKFLOW,event,created_at:new Date(now-time).toISOString(),conclusion,status});
let o=A.check([run('push',300000)],now);
assert.equal(o.status,'AWAITING_FIRST_SCHEDULE');assert.equal(o.alert,false);
o=A.check([run('push',3*3600000)],now);
assert.equal(o.status,'SCHEDULE_UNVERIFIED_OR_STALE');assert.equal(o.alert,true);
o=A.check([run('push',300000),run('schedule',1800000)],now);
assert.equal(o.status,'VERIFIED_SCHEDULE_RECENT');assert.equal(o.alert,false);
assert.equal(o.scheduled_runs_in_window,1);
assert.equal(o.cadence.cadence_status,'TOO_FEW_SCHEDULED_SUCCESSES');
const slow=A.check([run('schedule',300000),run('schedule',60*60000)],now);
assert.equal(slow.cadence.cadence_status,'GAPS_OVER_25_MINUTES');
assert.equal(slow.cadence.successful_intervals_minutes[0],55);
o=A.check([run('schedule',3*3600000)],now);
assert.equal(o.status,'SCHEDULE_UNVERIFIED_OR_STALE');
o=A.check([run('schedule',100000,'', 'in_progress')],now);
assert.equal(o.status,'SCHEDULED_RUN_IN_PROGRESS');assert.equal(o.alert,false);
o=A.check([run('schedule',100000,'failure')],now);
assert.equal(o.alert,true);
o=A.check([],now);assert.equal(o.alert,true);
assert.throws(()=>A.check({},now),/Invalid GitHub/);
console.log('v6.7.1 schedule audit checks passed');
