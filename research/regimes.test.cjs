const assert=require('node:assert/strict');
const R=require('./regimes.cjs'),C=require('../v61-core.js');
const b=Array.from({length:500},(_,i)=>({t:i*300000,o:100+i*.015,h:100.4+i*.015,l:99.6+i*.015,c:100+i*.015,v:12}));
assert.equal(C.valid(b),true);
assert.equal(R.regime(b,63),null);
const x=R.regime(b,90);
assert.ok(['UP_TREND','DOWN_TREND','RANGE'].includes(x.direction));
assert.ok(['LOW_VOL','MID_VOL','HIGH_VOL'].includes(x.volatility));
const counts=R.classify(b);
assert.equal(Object.values(counts).reduce((a,v)=>a+v,0),b.length-64);
const none=R.study(b,()=>null);
assert.equal(Object.keys(none.strategies).length,7);
assert.equal(none.strategies.fusion.historical_trades,0);
const yes=R.study(b,()=>({side:'LONG'}));
assert.ok(yes.strategies.fusion.historical_trades>0);
assert.equal(yes.strategies.fusion.periods.length,3);
assert.ok(yes.strategies.fusion.entire_window.caution.includes('NOT proof'));
const t=R.tag(b,[{signalIndex:110,grossPct:-1,reason:'STOP'},{signalIndex:111,grossPct:1.5,reason:'TARGET'}]);
assert.equal(t.stop_exit_count,1);
assert.equal(t.target_exit_count,1);
assert.equal(Object.values(t.grouped).reduce((a,v)=>a+v.count,0),2);
assert.throws(()=>R.study([...b.slice(0,10),...b.slice(11)],()=>null),/invalid/);
console.log('v6.6 market intelligence offline tests passed');
